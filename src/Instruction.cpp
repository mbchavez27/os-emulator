#include <algorithm>
#include <random>
#include <stdexcept>
#include <type_traits>
#include <utility>

Operand Operand::variable(std::string name)
{
    return Operand{false, std::move(name), 0};
}

Operand Operand::literal(uint16_t value)
{
    return Operand{true, {}, value};
}

namespace
{

constexpr int kMaxForDepth = 3;
constexpr uint32_t kMaxForBody = 10;

struct GeneratorState
{
    std::mt19937 rng;
    std::vector<std::string> variables;
    std::size_t nextVariable = 0;
};

std::string nextVariableName(GeneratorState &state)
{
    std::string name = state.nextVariable == 0
                           ? std::string{"x"}
                           : "x" + std::to_string(state.nextVariable);
    ++state.nextVariable;
    state.variables.push_back(name);
    return name;
}

std::string ensureVariable(GeneratorState &state)
{
    if (state.variables.empty())
    {
        return nextVariableName(state);
    }

    std::uniform_int_distribution<std::size_t> pick(0, state.variables.size() - 1);
    return state.variables[pick(state.rng)];
}

Operand randomOperand(GeneratorState &state)
{
    std::uniform_int_distribution<int> choice(0, 1);
    if (!state.variables.empty() && choice(state.rng) == 0)
    {
        return Operand::variable(ensureVariable(state));
    }

    std::uniform_int_distribution<int> value(0, 65535);
    return Operand::literal(static_cast<uint16_t>(value(state.rng)));
}

PrintInstruction makePrint(GeneratorState &state, const std::string &processName)
{
    std::uniform_int_distribution<int> form(0, 1);
    if (form(state.rng) == 0 || state.variables.empty())
    {
        return {"Hello world from " + processName + "!", std::nullopt};
    }
    return {"Value from: ", ensureVariable(state)};
}

Instruction makeSimple(GeneratorState &state, Op op, const std::string &processName)
{
    if (op == Op::PRINT)
    {
        return Instruction{makePrint(state, processName)};
    }

    if (op == Op::DECLARE)
    {
        std::uniform_int_distribution<int> value(0, 65535);
        return Instruction{DeclareInstruction{nextVariableName(state),
                                              static_cast<uint16_t>(value(state.rng))}};
    }

    if (op == Op::ADD || op == Op::SUBTRACT)
    {
        const std::string target = ensureVariable(state);
        Operand lhs = randomOperand(state);
        Operand rhs = randomOperand(state);

        if (op == Op::ADD)
        {
            return Instruction{AddInstruction{target, std::move(lhs), std::move(rhs)}};
        }
        return Instruction{SubtractInstruction{target, std::move(lhs), std::move(rhs)}};
    }

    if (op == Op::SLEEP)
    {
        std::uniform_int_distribution<int> ticks(1, 255);
        return Instruction{SleepInstruction{static_cast<uint8_t>(ticks(state.rng))}};
    }

    throw std::logic_error("FOR must be generated by generateSequence");
}

std::vector<Instruction> generateSequence(GeneratorState &state,
                                          uint32_t budget,
                                          int forDepth,
                                          const std::string &processName)
{
    std::vector<Instruction> instructions;
    instructions.reserve(budget);

    while (budget > 0)
    {
        const bool canFor = forDepth < kMaxForDepth && budget >= 2;

        // FOR is the last enumerator, so the picked value maps straight to Op.
        std::uniform_int_distribution<int> opPick(0, canFor ? 5 : 4);
        const Op op = static_cast<Op>(opPick(state.rng));

        if (op == Op::FOR)
        {
            const uint32_t maxBody = std::min<uint32_t>(budget - 1, kMaxForBody);
            std::uniform_int_distribution<uint32_t> bodyPick(1, maxBody);
            const uint32_t bodyBudget = bodyPick(state.rng);

            std::uniform_int_distribution<int> repeatsPick(2, 5);

            ForInstruction loop;
            loop.repeats = static_cast<uint16_t>(repeatsPick(state.rng));
            loop.body = generateSequence(state, bodyBudget, forDepth + 1, processName);

            instructions.push_back(Instruction{std::move(loop)});
            budget -= 1 + bodyBudget;
        }
        else
        {
            instructions.push_back(makeSimple(state, op, processName));
            --budget;
        }
    }

    return instructions;
}

std::string operandText(const Operand &operand)
{
    return operand.isLiteral ? std::to_string(operand.value) : operand.name;
}

void appendInstruction(std::string &out, const Instruction &instruction, int indent)
{
    const std::string pad(static_cast<std::size_t>(indent) * 2, ' ');

    std::visit(
        [&](const auto &payload) {
            using T = std::decay_t<decltype(payload)>;
            if constexpr (std::is_same_v<T, PrintInstruction>)
            {
                out += pad + "PRINT (\"" + payload.text + "\"";
                if (payload.variable)
                {
                    out += " + " + *payload.variable;
                }
                out += ")\n";
            }
            else if constexpr (std::is_same_v<T, DeclareInstruction>)
            {
                out += pad + "DECLARE (" + payload.name + ", " +
                       std::to_string(payload.value) + ")\n";
            }
            else if constexpr (std::is_same_v<T, AddInstruction> ||
                               std::is_same_v<T, SubtractInstruction>)
            {
                const char *name =
                    std::is_same_v<T, AddInstruction> ? "ADD" : "SUBTRACT";
                out += pad + name + " (" + payload.target + ", " +
                       operandText(payload.lhs) + ", " + operandText(payload.rhs) + ")\n";
            }
            else if constexpr (std::is_same_v<T, SleepInstruction>)
            {
                out += pad + "SLEEP (" + std::to_string(payload.ticks) + ")\n";
            }
            else
            {
                out += pad + "FOR (\n";
                for (const Instruction &child : payload.body)
                {
                    appendInstruction(out, child, indent + 1);
                }
                out += pad + ", " + std::to_string(payload.repeats) + ")\n";
            }
        },
        instruction.payload);
}

} // namespace

std::size_t Program::countInstructions(const std::vector<Instruction> &instructions)
{
    std::size_t total = 0;
    for (const Instruction &instruction : instructions)
    {
        ++total;
        if (const auto *loop = std::get_if<ForInstruction>(&instruction.payload))
        {
            total += countInstructions(loop->body);
        }
    }
    return total;
}

std::size_t Program::instructionCount() const
{
    return countInstructions(instructions);
}

std::string Program::toString() const
{
    std::string out;
    for (const Instruction &instruction : instructions)
    {
        appendInstruction(out, instruction, 0);
    }
    return out;
}

Op opOf(const Instruction &instruction)
{
    return std::visit(
        [](const auto &payload) -> Op {
            using T = std::decay_t<decltype(payload)>;
            if constexpr (std::is_same_v<T, PrintInstruction>)         return Op::PRINT;
            else if constexpr (std::is_same_v<T, DeclareInstruction>)  return Op::DECLARE;
            else if constexpr (std::is_same_v<T, AddInstruction>)      return Op::ADD;
            else if constexpr (std::is_same_v<T, SubtractInstruction>) return Op::SUBTRACT;
            else if constexpr (std::is_same_v<T, SleepInstruction>)    return Op::SLEEP;
            else                                                       return Op::FOR;
        },
        instruction.payload);
}

Program generateProgram(const Config &config,
                        const std::string &processName,
                        std::uint32_t seed)
{
    if (config.minIns == 0 || config.minIns > config.maxIns)
    {
        throw std::invalid_argument("generateProgram requires 1 <= minIns <= maxIns");
    }

    GeneratorState state{std::mt19937(seed), {}, 0};

    std::uniform_int_distribution<uint32_t> sizePick(config.minIns, config.maxIns);

    Program program;
    program.instructions = generateSequence(state, sizePick(state.rng), 0, processName);
    return program;
}
